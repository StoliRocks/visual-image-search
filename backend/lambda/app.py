"""AWS Lambda handler for visual image search using SageMaker and OpenSearch.

This module provides API endpoints for searching similar images using feature vectors
generated by a SageMaker endpoint and stored in an OpenSearch KNN index.
"""

from __future__ import annotations

import base64
import json
import logging
from io import BytesIO
from os import environ
from typing import TYPE_CHECKING, Any
from urllib.parse import urlparse

import boto3
import requests
from opensearchpy import AWSV4SignerAuth, OpenSearch, RequestsHttpConnection

if TYPE_CHECKING:
    from mypy_boto3_s3 import S3Client
    from mypy_boto3_sagemaker_runtime import SageMakerRuntimeClient

# Configure logging
logger = logging.getLogger(__name__)
logger.setLevel(logging.INFO)

# Global clients (reused across Lambda invocations)
sm_runtime_client: SageMakerRuntimeClient = boto3.client("sagemaker-runtime")
s3_client: S3Client = boto3.client("s3")

# Constants
DEFAULT_K_NEIGHBORS = 3
PRESIGNED_URL_EXPIRATION = 300  # 5 minutes
REQUEST_TIMEOUT = 30
INDEX_NAME = "idx_zalando"


class ImageSearchError(Exception):
    """Custom exception for image search errors."""

    def __init__(self, status_code: int, message: str) -> None:
        self.status_code = status_code
        self.message = message
        super().__init__(message)


def get_opensearch_client() -> OpenSearch:
    """Create and return an authenticated OpenSearch client.

    Returns:
        Configured OpenSearch client with AWS authentication
    """
    region = environ["AWS_REGION"]
    endpoint = environ["ES_ENDPOINT"]

    credentials = boto3.Session().get_credentials()
    auth = AWSV4SignerAuth(credentials, region, "es")

    return OpenSearch(
        hosts=[{"host": endpoint, "port": 443}],
        http_auth=auth,
        use_ssl=True,
        verify_certs=True,
        connection_class=RequestsHttpConnection,
    )


def get_features(image_bytes: BytesIO) -> list[float]:
    """Extract feature vector from image using SageMaker endpoint.

    Args:
        image_bytes: Image data as BytesIO object

    Returns:
        List of feature values from the model

    Raises:
        ImageSearchError: If feature extraction fails
    """
    sagemaker_endpoint = environ["SM_ENDPOINT"]

    try:
        response = sm_runtime_client.invoke_endpoint(
            EndpointName=sagemaker_endpoint,
            ContentType="application/x-image",
            Body=image_bytes.getvalue(),
        )
        response_body = json.loads(response["Body"].read())
        return response_body["predictions"][0]
    except Exception as e:
        logger.error("Failed to extract features: %s", e)
        raise ImageSearchError(500, f"Feature extraction failed: {e}") from e


def get_neighbors(
    features: list[float],
    client: OpenSearch,
    k_neighbors: int = DEFAULT_K_NEIGHBORS,
) -> list[str]:
    """Find k-nearest neighbors in OpenSearch index.

    Args:
        features: Feature vector for similarity search
        client: OpenSearch client
        k_neighbors: Number of similar images to return

    Returns:
        List of S3 URIs for similar images

    Raises:
        ImageSearchError: If the search fails
    """
    try:
        response = client.search(
            index=INDEX_NAME,
            body={
                "size": k_neighbors,
                "query": {
                    "knn": {
                        "zalando_img_vector": {
                            "vector": features,
                            "k": k_neighbors,
                        }
                    }
                },
            },
            request_timeout=REQUEST_TIMEOUT,
        )

        hits = response["hits"]["hits"]
        return [hit["_source"]["image"] for hit in hits]
    except Exception as e:
        logger.error("OpenSearch query failed: %s", e)
        raise ImageSearchError(500, f"Similarity search failed: {e}") from e


def generate_presigned_urls(s3_uris: list[str]) -> list[str]:
    """Generate presigned URLs for S3 objects.

    Args:
        s3_uris: List of S3 URIs (s3://bucket/key format)

    Returns:
        List of presigned HTTPS URLs
    """
    presigned_urls = []
    for uri in s3_uris:
        parsed = urlparse(uri)
        url = s3_client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": parsed.netloc,
                "Key": parsed.path.lstrip("/"),
            },
            ExpiresIn=PRESIGNED_URL_EXPIRATION,
        )
        presigned_urls.append(url)
    return presigned_urls


def download_image(url: str) -> BytesIO:
    """Download an image from a URL.

    Args:
        url: Public URL of the image

    Returns:
        Image data as BytesIO object

    Raises:
        ImageSearchError: If download fails
    """
    try:
        response = requests.get(url, timeout=REQUEST_TIMEOUT)
        response.raise_for_status()
        return BytesIO(response.content)
    except requests.RequestException as e:
        logger.error("Failed to download image from %s: %s", url, e)
        raise ImageSearchError(400, f"Failed to download image: {e}") from e


def create_response(
    status_code: int,
    body: dict[str, Any],
) -> dict[str, Any]:
    """Create an API Gateway response with CORS headers.

    Args:
        status_code: HTTP status code
        body: Response body as dictionary

    Returns:
        Formatted API Gateway response
    """
    return {
        "statusCode": status_code,
        "headers": {
            "Access-Control-Allow-Origin": "*",
            "Access-Control-Allow-Headers": "Content-Type,X-Amz-Date,Authorization,X-Api-Key,X-Amz-Security-Token",
            "Access-Control-Allow-Methods": "GET,POST,OPTIONS",
            "Content-Type": "application/json",
        },
        "body": json.dumps(body),
    }


def lambda_handler(event: dict[str, Any], context: Any) -> dict[str, Any]:
    """AWS Lambda handler for image similarity search.

    Supports two endpoints:
    - POST /postURL: Search using a public image URL
    - POST /postImage: Search using a base64-encoded image

    Args:
        event: API Gateway event
        context: Lambda context (unused)

    Returns:
        API Gateway response with presigned URLs to similar images
    """
    try:
        # Parse request
        body = json.loads(event.get("body", "{}"))
        k_neighbors = body.get("k", DEFAULT_K_NEIGHBORS)

        # Validate k parameter
        if not isinstance(k_neighbors, int) or k_neighbors < 1 or k_neighbors > 10:
            return create_response(400, {"error": "k must be an integer between 1 and 10"})

        # Get image based on endpoint
        path = event.get("path", "")
        if path == "/postURL":
            url = body.get("url")
            if not url:
                return create_response(400, {"error": "Missing 'url' in request body"})
            image = download_image(url)
        elif path == "/postImage":
            img_string = body.get("base64img")
            if not img_string:
                return create_response(400, {"error": "Missing 'base64img' in request body"})
            try:
                image = BytesIO(base64.b64decode(img_string))
            except Exception as e:
                return create_response(400, {"error": f"Invalid base64 encoding: {e}"})
        else:
            return create_response(404, {"error": f"Unknown path: {path}"})

        # Initialize OpenSearch client
        os_client = get_opensearch_client()

        # Process image
        features = get_features(image)
        s3_uris = get_neighbors(features, os_client, k_neighbors=k_neighbors)
        presigned_urls = generate_presigned_urls(s3_uris)

        logger.info("Successfully found %d similar images", len(presigned_urls))

        return create_response(200, {"images": presigned_urls})

    except ImageSearchError as e:
        logger.error("Image search error: %s", e.message)
        return create_response(e.status_code, {"error": e.message})
    except json.JSONDecodeError as e:
        logger.error("Invalid JSON in request body: %s", e)
        return create_response(400, {"error": "Invalid JSON in request body"})
    except Exception as e:
        logger.exception("Unexpected error in lambda_handler")
        return create_response(500, {"error": "Internal server error"})
